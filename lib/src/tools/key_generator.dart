/// Converts a translation key like `home.sign_in-title` to `homeSignInTitle`.
String keyToIdentifier(String key) {
  final words = key
      .replaceAllMapped(RegExp(r'([a-z0-9])([A-Z])'), (m) => '${m[1]} ${m[2]}')
      .split(RegExp(r'[^A-Za-z0-9]+'))
      .where((w) => w.isNotEmpty)
      .toList();
  if (words.isEmpty) return 'key';
  final buffer = StringBuffer(words.first.toLowerCase());
  for (final w in words.skip(1)) {
    buffer.write(w[0].toUpperCase() + w.substring(1).toLowerCase());
  }
  var id = buffer.toString();
  if (RegExp(r'^[0-9]').hasMatch(id)) id = 'k$id';
  if (_reserved.contains(id)) id = '${id}Key';
  return id;
}

String _escape(String s) =>
    s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');

String _docLine(String value) {
  final oneLine = value.replaceAll(RegExp(r'\s+'), ' ').trim();
  return oneLine.length > 80 ? '${oneLine.substring(0, 77)}...' : oneLine;
}

/// Generates Dart source with one constant per translation key in [data].
///
/// Returns the source; collisions between generated names are suffixed with a
/// number and reported through [warnings].
String generateKeysSource(
  Map<String, dynamic> data, {
  String className = 'AppTrans',
  String command = 'dart run playx_localization:generate',
  List<String>? warnings,
}) {
  final flat = flattenTranslations(data);
  final used = <String>{};
  final b = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by `$command`.')
    ..writeln()
    ..writeln('/// Translation keys, usable with `.tr()` and `.plural()`.')
    ..writeln('abstract class $className {')
    ..writeln('  $className._();');

  for (final entry in flat.entries) {
    var name = keyToIdentifier(entry.key);
    if (!used.add(name)) {
      var i = 2;
      while (!used.add('$name$i')) {
        i++;
      }
      warnings?.add(
        'Key "${entry.key}" collides with another key; generated as $name$i.',
      );
      name = '$name$i';
    }
    b
      ..writeln()
      ..writeln('  /// ${_docLine(entry.value)}')
      ..writeln("  static const $name = '${_escape(entry.key)}';");
  }
  b.writeln('}');
  return b.toString();
}

const generateUsage = '''
Generates a Dart class with a constant for every key in a translation file.

Usage: dart run playx_localization:generate [options]

  --source <file>   Base translation file (default: assets/translations/en.json)
  --output <file>   Dart file to write (default: lib/generated/app_trans.dart)
  --class <name>    Generated class name (default: AppTrans)
  --check           Do not write; exit 1 if the output file is out of date
  --help            Show this help
''';

/// Entry point of `generate`. Returns the process exit code.
Future<int> runGenerate(
  List<String> args, {
  StringSink? out,
  StringSink? err,
}) async {
  out ??= stdout;
  err ??= stderr;
  final cli = CliArgs.parse(args, flagNames: {'check', 'help'});
  if (cli.has('help')) {
    out.write(generateUsage);
    return 0;
  }
  final source = cli['source'] ?? 'assets/translations/en.json';
  final output = cli['output'] ?? 'lib/generated/app_trans.dart';
  final className = cli['class'] ?? 'AppTrans';

  if (!RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(className)) {
    err.writeln('Invalid class name "$className".');
    return 64;
  }
  if (!File(source).existsSync()) {
    err.writeln('Source file not found: $source');
    return 66;
  }

  final Map<String, dynamic> data;
  try {
    data = await TranslationFile.fromPath(source).load();
  } catch (e) {
    err.writeln('Could not read $source: $e');
    return 65;
  }

  final warnings = <String>[];
  final code = generateKeysSource(
    data,
    className: className,
    warnings: warnings,
  );
  for (final w in warnings) {
    out.writeln('warning: $w');
  }

  final file = File(output);
  if (cli.has('check')) {
    final current = file.existsSync() ? file.readAsStringSync() : null;
    if (current != code) {
      err.writeln(
        '$output is out of date. Run: dart run playx_localization:generate',
      );
      return 1;
    }
    out.writeln('$output is up to date.');
    return 0;
  }

  file.parent.createSync(recursive: true);
  file.writeAsStringSync(code);
  out.writeln(
    'Generated $className with ${flattenTranslations(data).length} keys -> $output',
  );
  return 0;
}
